"""Train a decision tree on the IoT Project dataset and export it as C code for the ESP32.

The tree becomes plain if-else statements in firmware/iot_project/water_model.h, so the
ESP32 classifies the water itself (no Wi-Fi or laptop needed).

Usage:
    python export_tree.py --csv iot_project_dataset.csv
    python export_tree.py --csv data.csv --max-depth 3 --features tds turb

Then upload the firmware again (the header is picked up automatically).
Retrain and export again whenever the sensors are re-calibrated.
"""
import argparse
import os
import sys

import numpy as np
from sklearn.metrics import accuracy_score, classification_report
from sklearn.tree import DecisionTreeClassifier, _tree, export_text

from train_classifier import LABEL_ORDER, load, time_split

# Dataset column -> firmware argument of classifyWaterFromReadings()
FIRMWARE_ARGS = ["tds", "tds_v", "turb", "turb_v", "t_tank"]
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "iot_project", "water_model.h")


def tree_to_c(clf, features, indent="  "):
    """Turns a trained sklearn decision tree into nested C if-else statements (returns the lines)."""
    t = clf.tree_
    lines = []

    def node(i, depth):
        pad = indent * depth
        if t.feature[i] == _tree.TREE_UNDEFINED:
            counts = t.value[i][0]
            cls = int(np.argmax(counts))
            share = counts[cls] / counts.sum()
            lines.append(f"{pad}return {cls};  // {clf.classes_[cls]} ({share:.0%} of training rows here)")
            return
        name, thr = features[t.feature[i]], float(t.threshold[i])
        lines.append(f"{pad}if ({name} <= {thr:.6f}f) {{")
        node(t.children_left[i], depth + 1)
        lines.append(f"{pad}}} else {{")
        node(t.children_right[i], depth + 1)
        lines.append(f"{pad}}}")

    node(0, 1)
    return "\n".join(lines)


def main():
    """Trains the tree, prints its accuracy and writes firmware/iot_project/water_model.h."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", required=True)
    ap.add_argument("--features", nargs="+", default=["tds", "turb"])
    ap.add_argument("--max-depth", type=int, default=4)
    ap.add_argument("--test-frac", type=float, default=0.25)
    ap.add_argument("--include-sim", action="store_true", help="also use simulator rows (pipeline test only)")
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()

    bad = [f for f in a.features if f not in FIRMWARE_ARGS]
    if bad:
        sys.exit(f"The ESP32 only has these values: {FIRMWARE_ARGS}. Not available: {bad}")

    df = load(a.csv, a.features, a.include_sim)
    counts = df["label"].value_counts()
    if len(counts) < 2 or counts.min() < 20:
        sys.exit("Need at least 2 labels with 20+ rows each.")
    train, test = time_split(df, a.test_frac)

    # Check accuracy on held-out data first, then train the final tree on everything
    check = DecisionTreeClassifier(max_depth=a.max_depth, random_state=42).fit(train[a.features], train["label"])
    pred = check.predict(test[a.features])
    labels = [l for l in LABEL_ORDER if l in counts.index] + [l for l in counts.index if l not in LABEL_ORDER]
    print(f"Test accuracy (time-ordered split): {accuracy_score(test['label'], pred):.3f}")
    print(classification_report(test["label"], pred, labels=labels, zero_division=0))

    clf = DecisionTreeClassifier(max_depth=a.max_depth, random_state=42).fit(df[a.features], df["label"])
    classes = list(clf.classes_)
    names = {"clear": "CLEAR", "slightly_turbid": "SLIGHT", "dirty": "DIRTY"}
    short = [names.get(c, c.upper()[:6]) for c in classes]   # fits on the OLED
    body = tree_to_c(clf, a.features)

    header = f"""// Water-condition decision tree for the ESP32.
// Generated by ml/export_tree.py from {os.path.basename(a.csv)} - do not edit by hand.
// Features: {', '.join(a.features)} | max depth {a.max_depth} | {len(df)} training rows
// Held-out accuracy: {accuracy_score(test['label'], pred):.3f}
#pragma once

#define WATER_MODEL_AVAILABLE 1
#define WATER_MODEL_CLASSES {len(classes)}

static const char* const WATER_LABELS[] = {{{', '.join(f'"{c}"' for c in classes)}}};
static const char* const WATER_SHORT[]  = {{{', '.join(f'"{s}"' for s in short)}}};

// Returns an index into WATER_LABELS.
inline int classifyWaterFromReadings(float tds, float tds_v, float turb, float turb_v, float t_tank) {{
  (void)tds; (void)tds_v; (void)turb; (void)turb_v; (void)t_tank;
{body}
}}
"""
    with open(a.out, "w") as f:
        f.write(header)
    print("Tree rules:\n" + export_text(clf, feature_names=list(a.features)))
    print(f"Wrote {os.path.normpath(a.out)}")


if __name__ == "__main__":
    main()
